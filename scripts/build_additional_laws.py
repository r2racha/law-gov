def write_ts(path: Path, export_prefix: str, articles: list[dict], questions: list[dict]) -> None:
    sections = []
    for article in articles:
        if article["section"] not in sections:
            sections.append(article["section"])
    question_rows = []
    categories = ["error"] * 5 + ["accuracy"] * 5 + ["analysis"] * 5 + ["scenario"] * 5
    for index, item in enumerate(questions):
        reference = re.search(r"(?:ข้อ|มาตรา)\s*([0-9/]+)", f"{item['question']} {item['explanation']}")
        question_rows.append({
            **item,
            "id": index + 1,
            "category": categories[index],
            "articleRef": f"ข้อ {reference.group(1)}" if reference and export_prefix == "liability" else (f"มาตรา {reference.group(1)}" if reference else "ตัวบทที่เกี่ยวข้อง"),
        })
    lines = [
        "/**",
        " * Design reminder — ห้องเรียนพาสเทลแบบเล่าเรื่อง:",
        " * This dataset is parsed from the legal text supplied by the user; summaries quote or condense the article opening without adding legal opinions.",
        " */",
        'import type { LawArticle, QuizQuestion } from "@/data/law";',
        "",
        f"export const {export_prefix}Sections = {json.dumps(sections, ensure_ascii=False)} as const;",
        f"export const {export_prefix}Articles: LawArticle[] = {json.dumps(articles, ensure_ascii=False, indent=2)};",
        f"export const {export_prefix}Quiz: QuizQuestion[] = {json.dumps(question_rows, ensure_ascii=False, indent=2)};",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")



def clean(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def article_intro(text: str, max_len: int = 98) -> str:
    text = clean(re.sub(r"\[\^[^\]]+\]", "", text))
    if len(text) <= max_len:
        return text
    cut = text[:max_len].rsplit(" ", 1)[0]
    return f"{cut}…"


def parse_law(path: Path, marker: str, label: str) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    section = "บททั่วไป"
    current_number: str | None = None
    content: list[str] = []
    items: list[dict] = []

    def flush() -> None:
        nonlocal current_number, content
        if not current_number:
            return
        law_text = "\n".join(line for line in content if line.strip()).strip()
        if not law_text or current_number in {item["number"] for item in items}:
            return
        if "ผู้ลงนาม/ผู้รับรองเอกสาร" in law_text:
            return
        intro = article_intro(law_text)
        items.append({
            "number": current_number,
            "section": section,
            "keyPoint": intro,
            "plainSummary": intro,
            "lawText": law_text,
        })
        current_number, content = None, []

    heading = re.compile(rf"^#### {re.escape(marker)}\s+([0-9/]+)")
    for line in lines:
        if line.startswith("## ผู้ลงนาม") or line.startswith("## หมายเหตุ"):
            flush()
            break
        if line.startswith("## หมวด") or line.startswith("## บทเฉพาะกาล"):
            flush()
            section = clean(line.lstrip("#").strip())
            continue
        match = heading.match(line)
        if match:
            flush()
            current_number = match.group(1)
            continue
        if current_number:
            content.append(line)
    flush()
    return items



def clean(text: str) -> str:
    text = re.sub(r"(?m)^\s*[๐-๙]+\s+มาตรา.*\n?", "", text)
    text = re.sub(r"(?m)^\s*[๐-๙]+\s+พระราชกฤษฎีกา.*\n?", "", text)
    text = re.sub(r"\n[๑-๙]+\s+ราชกิจจานุเบกษา[^\n]*", "", text)
    text = re.sub(r"\n[๑-๙]+\s+มาตรา[^\n]*พระราชกฤษฎีกา[^\n]*(?:\n\s*(?:บ้านเมือง|ที่ดี|พ\.ศ\.)[^\n]*)*", "", text)
    text = re.sub(r"\nหมวด\s+[๐-๙]+\s*(?:\n[^\n]+)?", "", text)
    section_titles = {
        "การบริหารกิจการบ้านเมืองที่ดี",
        "การบริหารราชการเพื่อให้เกิดประโยชน์สุขของประชาชน",
        "การบริหารราชการเพื่อให้เกิดผลสัมฤทธิ์ต่อภารกิจของรัฐ",
        "การบริหารราชการอย่างมีประสิทธิภาพ",
        "และเกิดความคุ้มค่าในเชิงภารกิจของรัฐ",
        "การลดขั้นตอนการปฏิบัติงาน",
        "การปรับปรุงภารกิจของส่วนราชการ",
        "การอำนวยความสะดวกและการตอบสนองความต้องการของประชาชน",
        "การประเมินผลการปฏิบัติราชการ",
        "บทเบ็ดเสร็จ",
    }
    text = "\n".join(line for line in text.splitlines() if line.strip() not in section_titles)
    text = re.sub(r"\n\s*\n", "\n", text)
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def parse_articles(source: str):
    pattern = re.compile(r"(?m)^มาตรา\s+([๐-๙]+)(?=\s|$)")
    matches = list(pattern.finditer(source))
    articles = []
    seen = set()
    for i, match in enumerate(matches):
        raw_digits = arabic(match.group(1))
        number = int(raw_digits)
        if number > 53 and len(raw_digits) > 1 and int(raw_digits[:-1]) <= 53:
            number = int(raw_digits[:-1])
        if not 1 <= number <= 53 or number in seen:
            continue
        end = matches[i + 1].start() if i + 1 < len(matches) else len(source)
        raw = source[match.start():end]
        raw = re.sub(rf"^มาตรา\s+{re.escape(match.group(1))}", f"มาตรา {number}", raw)
        raw = clean(raw)
        seen.add(number)
        summary, key = NOTES[number]
        articles.append({"number": str(number), "section": section_for(number), "lawText": raw, "plainSummary": summary, "keyPoint": key})
    return sorted(articles, key=lambda item: int(item["number"]))



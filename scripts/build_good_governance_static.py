    articles = parse_articles(SOURCE.read_text(encoding="utf-8"))
    if [int(item["number"]) for item in articles] != list(range(1, 54)):
        raise RuntimeError("Could not parse all 53 articles from consolidated source")
    quiz = [{"id": index + 1, "category": row[0], "articleRef": "มาตรา " + row[1], "question": row[2], "choices": row[3], "answerIndex": row[4], "explanation": row[5]} for index, row in enumerate(QUIZ)]
